/**
 * 1. Generate Sitemap XML
 */
function generateSitemap() {
  const today = new Date().toISOString().split('T')[0];
  let xml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  xml += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;

  // Root & Category Hubs
  xml += `  <url>\n    <loc>https://toolsbuddy.pages.dev/</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>1.0</priority>\n  </url>\n`;

  Object.values(categories).forEach(cat => {
    xml += `  <url>\n    <loc>https://toolsbuddy.pages.dev/${cat.url}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>0.9</priority>\n  </url>\n`;
  });

  // Active Tools
  activeTools.forEach(tool => {
    xml += `  <url>\n    <loc>https://toolsbuddy.pages.dev/${tool.url}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>${tool.priority === 1 ? '0.9' : '0.8'}</priority>\n  </url>\n`;
  });

  // Legal & Standalone
  ['privacy-policy.html', 'terms.html', 'ebook-buddy.html'].forEach(f => {
    if (fs.existsSync(path.join(ROOT_DIR, f))) {
      xml += `  <url>\n    <loc>https://toolsbuddy.pages.dev/${f}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.5</priority>\n  </url>\n`;
    }
  });

  xml += `</urlset>\n`;
  fs.writeFileSync(SITEMAP_FILE, xml, 'utf8');
  console.log(`Updated sitemap.xml with ${activeTools.length + 5} URLs.`);
}

/**
 * 2. Generate Search Index JS
 */
function generateSearchIndex() {
  const searchItems = allTools.map(t => ({
    id: t.id,
    title: t.title,
    category: t.category,
    url: t.status === 'active' ? t.url : `${categories[t.category].url}#${t.id}`,
    desc: t.description,
    keywords: t.keywords || [],
    status: t.status
  }));

  const jsContent = `/**
 * ToolsBuddy - Master Client-Side Search Index
 * Auto-generated by tools/sync.js
 */
window.TB_TOOLS_INDEX = ${JSON.stringify(searchItems, null, 2)};
`;
  fs.writeFileSync(SEARCH_INDEX_FILE, jsContent, 'utf8');
  console.log(`Generated js/search-index.js with ${searchItems.length} searchable items.`);
}

